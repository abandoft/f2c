#include "core/generated/private.h"

void f2c_emit_descriptor_declaration(Buffer *output) {
    f2c_buffer_append(output, "/* Qualified/unqualified versions of a pointer have identical\n"
                              " * representation and alignment (ISO C17 6.2.5). The address\n"
                              " * union transports qualification without discarding casts;\n"
                              " * each Fortran scope selects its own access-qualified view. */\n"
                              "typedef struct f2c_descriptor {\n"
                              "    union {\n"
                              "        void *data;\n"
                              "        const void *readonly_data;\n"
                              "        volatile void *volatile_data;\n"
                              "        const volatile void *readonly_volatile_data;\n"
                              "    };\n"
                              "    unsigned int storage_qualifiers;\n"
                              "    bool deallocatable;\n"
                              "    size_t element_size;\n"
                              "    size_t rank;\n"
                              "    int64_t lower[15];\n"
                              "    int64_t extent[15];\n"
                              "    ptrdiff_t stride[15];\n"
                              "    size_t character_length;\n"
                              "} f2c_descriptor;\n");
}

void f2c_emit_descriptor_contiguous_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED void f2c_descriptor_read_record(void *destination,\n"
        "    const f2c_descriptor *source, ptrdiff_t offset, size_t length) {\n"
        "    if (length == 0U) return;\n"
        "    if (source == NULL || destination == NULL || source->readonly_data == NULL) abort();\n"
        "    if ((source->storage_qualifiers & 1U) != 0U) {\n"
        "        const volatile unsigned char *input =\n"
        "            (const volatile unsigned char *)source->readonly_volatile_data + offset;\n"
        "        unsigned char *output = (unsigned char *)destination;\n"
        "        for (size_t byte = 0U; byte < length; ++byte) output[byte] = input[byte];\n"
        "    } else {\n"
        "        memcpy(destination, (const unsigned char *)source->readonly_data + offset, "
        "length);\n"
        "    }\n"
        "}\n"
        "static inline F2C_UNUSED void f2c_descriptor_write_record(const f2c_descriptor *target,\n"
        "    ptrdiff_t offset, const void *source, size_t length) {\n"
        "    if (length == 0U) return;\n"
        "    if (target == NULL || source == NULL || target->readonly_data == NULL) abort();\n"
        "    if ((target->storage_qualifiers & 1U) != 0U) {\n"
        "        volatile unsigned char *output =\n"
        "            (volatile unsigned char *)target->volatile_data + offset;\n"
        "        const unsigned char *input = (const unsigned char *)source;\n"
        "        for (size_t byte = 0U; byte < length; ++byte) output[byte] = input[byte];\n"
        "    } else {\n"
        "        memcpy((unsigned char *)target->data + offset, source, length);\n"
        "    }\n"
        "}\n"
        "static inline F2C_UNUSED void f2c_descriptor_prepare_contiguous(f2c_descriptor "
        "*destination,\n"
        "    const f2c_descriptor *source, bool character, bool copy_in) {\n"
        "    size_t count; size_t record_size; ptrdiff_t expected = 1;\n"
        "    if (destination == NULL || source == NULL || destination->data != NULL) abort();\n"
        "    count = f2c_descriptor_element_count(source);\n"
        "    record_size = f2c_descriptor_record_size(source, character);\n"
        "    if (record_size != 0U && count > SIZE_MAX / record_size) abort();\n"
        "    *destination = *source;\n"
        "    destination->data = malloc(count == 0U || record_size == 0U ? 1U : count * "
        "record_size);\n"
        "    if (destination->data == NULL) abort();\n"
        "    destination->storage_qualifiers = 0U;\n"
        "    destination->deallocatable = false;\n"
        "    for (size_t dimension = 0U; dimension < source->rank; ++dimension) {\n"
        "        destination->stride[dimension] = expected;\n"
        "        expected = f2c_descriptor_stride_extent(expected, "
        "(size_t)source->extent[dimension]);\n"
        "    }\n"
        "    if (copy_in && count != 0U && record_size != 0U) {\n"
        "        if (source->readonly_data == NULL || record_size > (size_t)PTRDIFF_MAX) abort();\n"
        "        for (size_t index = 0U; index < count; ++index) {\n"
        "            ptrdiff_t offset = f2c_descriptor_linear_offset(source, index);\n"
        "            ptrdiff_t bytes = f2c_descriptor_stride_multiply(offset, "
        "(ptrdiff_t)record_size);\n"
        "            f2c_descriptor_read_record((unsigned char *)destination->data +\n"
        "                index * record_size, source, bytes, record_size);\n"
        "        }\n"
        "    }\n"
        "}\n"
        "static inline F2C_UNUSED void f2c_descriptor_finish_contiguous(const f2c_descriptor "
        "*source,\n"
        "    f2c_descriptor *temporary, bool character, bool copy_out) {\n"
        "    size_t count; size_t record_size;\n"
        "    if (source == NULL || temporary == NULL || temporary->data == NULL) abort();\n"
        "    count = f2c_descriptor_element_count(source);\n"
        "    record_size = f2c_descriptor_record_size(source, character);\n"
        "    if (copy_out && count != 0U && record_size != 0U) {\n"
        "        if (source->readonly_data == NULL || record_size > (size_t)PTRDIFF_MAX) abort();\n"
        "        for (size_t index = 0U; index < count; ++index) {\n"
        "            ptrdiff_t offset = f2c_descriptor_linear_offset(source, index);\n"
        "            ptrdiff_t bytes = f2c_descriptor_stride_multiply(offset, "
        "(ptrdiff_t)record_size);\n"
        "            f2c_descriptor_write_record(source, bytes,\n"
        "                (const unsigned char *)temporary->data + index * record_size, "
        "record_size);\n"
        "        }\n"
        "    }\n"
        "    free(temporary->data);\n"
        "    memset(temporary, 0, sizeof(*temporary));\n"
        "}\n");
}

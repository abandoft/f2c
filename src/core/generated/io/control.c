#include "core/generated/private.h"

void f2c_emit_io_control_model(Buffer *output) {
    f2c_buffer_append(
        output,
        "typedef enum f2c_unit_delim { F2C_DELIM_NONE, F2C_DELIM_APOSTROPHE, "
        "F2C_DELIM_QUOTE } f2c_unit_delim;\n"
        "typedef enum f2c_format_round_mode { F2C_FORMAT_ROUND_UP, F2C_FORMAT_ROUND_DOWN, "
        "F2C_FORMAT_ROUND_ZERO, F2C_FORMAT_ROUND_NEAREST, F2C_FORMAT_ROUND_COMPATIBLE, "
        "F2C_FORMAT_ROUND_PROCESSOR } f2c_format_round_mode;\n"
        "typedef enum f2c_unit_sign { F2C_SIGN_PROCESSOR, F2C_SIGN_SUPPRESS, F2C_SIGN_PLUS } "
        "f2c_unit_sign;\n"
        "typedef struct f2c_io_controls { f2c_unit_delim delim; f2c_format_round_mode rounding; "
        "f2c_unit_sign sign; bool decimal_comma; } f2c_io_controls;\n");
}

void f2c_emit_io_control_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "typedef struct f2c_io_control_scope { f2c_io_stream *stream; f2c_io_controls saved; "
        "bool saved_active; } f2c_io_control_scope;\n"
        "static inline F2C_UNUSED f2c_io_controls f2c_io_unit_controls(int32_t unit) { "
        "f2c_io_controls controls = {F2C_DELIM_NONE, F2C_FORMAT_ROUND_PROCESSOR, "
        "F2C_SIGN_PROCESSOR, false}; f2c_unit_entry *entry = f2c_find_unit(unit); if (entry "
        "!= NULL && !entry->internal && entry->form == F2C_FORM_FORMATTED) { controls.delim "
        "= entry->delim; controls.rounding = entry->rounding; controls.sign = entry->sign; "
        "controls.decimal_comma = entry->decimal_comma; } return controls; }\n"
        "static inline F2C_UNUSED bool f2c_io_override_controls(f2c_io_controls *controls, "
        "const char *decimal, size_t decimal_length, const char *round, size_t round_length, "
        "const char *sign, size_t sign_length, const char *delim, size_t delim_length) { "
        "f2c_io_controls next = *controls; if (decimal != NULL) { if (f2c_option_equal("
        "decimal, decimal_length, \"point\")) next.decimal_comma = false; else if "
        "(f2c_option_equal(decimal, decimal_length, \"comma\")) next.decimal_comma = true; "
        "else return false; } if (round != NULL) { if (f2c_option_equal(round, round_length, "
        "\"up\")) next.rounding = F2C_FORMAT_ROUND_UP; else if (f2c_option_equal(round, "
        "round_length, \"down\")) next.rounding = F2C_FORMAT_ROUND_DOWN; else if "
        "(f2c_option_equal(round, round_length, \"zero\")) next.rounding = "
        "F2C_FORMAT_ROUND_ZERO; else if (f2c_option_equal(round, round_length, \"nearest\")) "
        "next.rounding = F2C_FORMAT_ROUND_NEAREST; else if (f2c_option_equal(round, "
        "round_length, \"compatible\")) next.rounding = F2C_FORMAT_ROUND_COMPATIBLE; else "
        "if (f2c_option_equal(round, round_length, \"processor_defined\")) next.rounding = "
        "F2C_FORMAT_ROUND_PROCESSOR; else return false; } if (sign != NULL) { if "
        "(f2c_option_equal(sign, sign_length, \"plus\")) next.sign = F2C_SIGN_PLUS; else if "
        "(f2c_option_equal(sign, sign_length, \"suppress\")) next.sign = F2C_SIGN_SUPPRESS; "
        "else if (f2c_option_equal(sign, sign_length, \"processor_defined\")) next.sign = "
        "F2C_SIGN_PROCESSOR; else return false; } if (delim != NULL) { if "
        "(f2c_option_equal(delim, delim_length, \"none\")) next.delim = F2C_DELIM_NONE; "
        "else if (f2c_option_equal(delim, delim_length, \"apostrophe\")) next.delim = "
        "F2C_DELIM_APOSTROPHE; else if (f2c_option_equal(delim, delim_length, \"quote\")) "
        "next.delim = F2C_DELIM_QUOTE; else return false; } *controls = next; return true; }\n"
        "static inline F2C_UNUSED bool f2c_io_enter_controls(f2c_io_control_scope *scope, "
        "f2c_io_stream *stream, int32_t unit, const char *decimal, size_t decimal_length, "
        "const char *round, size_t round_length, const char *sign, size_t sign_length, "
        "const char *delim, size_t delim_length) { if (stream == NULL || scope == NULL) "
        "return false; scope->stream = stream; scope->saved = stream->controls; "
        "scope->saved_active = stream->controls_active; if (!stream->controls_active) "
        "stream->controls = f2c_io_unit_controls(unit); stream->controls_active = true; "
        "if (f2c_child_io_depth == 0U) stream->list_character = false; "
        "return f2c_io_override_controls(&stream->controls, decimal, decimal_length, "
        "round, round_length, sign, sign_length, delim, delim_length); }\n"
        "static inline F2C_UNUSED void f2c_io_leave_controls(f2c_io_control_scope *scope) { "
        "if (scope != NULL && scope->stream != NULL) { scope->stream->controls = scope->saved; "
        "scope->stream->controls_active = scope->saved_active; scope->stream = NULL; } }\n"
        "static inline F2C_UNUSED int f2c_io_value_separator(const f2c_io_stream *stream) { "
        "return stream->controls.decimal_comma ? ';' : ','; }\n"
        "static inline F2C_UNUSED void f2c_io_copy_controls(f2c_io_stream *destination, "
        "const f2c_io_stream *source) { destination->controls = source->controls; "
        "destination->controls_active = source->controls_active; }\n");
}

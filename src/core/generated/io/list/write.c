#include "core/generated/private.h"

void f2c_emit_list_write_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED void f2c_io_write_real(f2c_io_stream *stream, double value, "
        "int precision) { char field[128], *decimal; int saved, count; struct lconv *locale; "
        "const char *point; size_t point_length, length; if (!f2c_io_begin_rounding("
        "stream->controls.rounding, value, precision, true, &saved)) { stream->error = true; "
        "return; } count = snprintf(field, sizeof(field), stream->controls.sign == "
        "F2C_SIGN_PLUS ? \"%+.*g\" : \"%.*g\", precision, value); f2c_io_end_rounding(saved); "
        "if (count < 0 || (size_t)count >= sizeof(field)) { stream->error = true; return; } "
        "length = (size_t)count; locale = localeconv(); point = locale != NULL ? "
        "locale->decimal_point : NULL; point_length = point != NULL ? strlen(point) : 0U; "
        "decimal = point_length != 0U ? strstr(field, point) : NULL; if (decimal != NULL) { "
        "size_t offset = (size_t)(decimal - field); decimal[0] = "
        "stream->controls.decimal_comma ? ',' : '.'; if (point_length > 1U) { "
        "memmove(decimal + 1U, decimal + point_length, length - offset - point_length + 1U); "
        "length -= point_length - 1U; } } (void)f2c_stream_write(field, length, stream); }\n"
        "static inline F2C_UNUSED void f2c_write_i8(f2c_io_stream *f, int8_t v) { "
        "f->list_character = false; f2c_stream_printf(f, f->controls.sign == F2C_SIGN_PLUS ? \" "
        "%+d\" : \" %d\", (int)v); }\n"
        "static inline F2C_UNUSED void f2c_write_i16(f2c_io_stream *f, int16_t v) { "
        "f->list_character = false; f2c_stream_printf(f, f->controls.sign == F2C_SIGN_PLUS ? \" "
        "%+d\" : \" %d\", (int)v); }\n"
        "static inline F2C_UNUSED void f2c_write_i32(f2c_io_stream *f, int32_t v) { "
        "f->list_character = false; f2c_stream_printf(f, f->controls.sign == F2C_SIGN_PLUS ? \" "
        "%+d\" : \" %d\", (int)v); }\n"
        "static inline F2C_UNUSED void f2c_write_i64(f2c_io_stream *f, int64_t v) { "
        "f->list_character = false; "
        "f2c_stream_printf(f, f->controls.sign == F2C_SIGN_PLUS ? \" %+lld\" : \" %lld\", "
        "(long long)v); }\n"
        "static inline F2C_UNUSED void f2c_write_float(f2c_io_stream *f, float v) { "
        "f->list_character = false; (void)f2c_stream_putc(' ', f); f2c_io_write_real(f, (double)v, "
        "FLT_DECIMAL_DIG); }\n"
        "static inline F2C_UNUSED void f2c_write_double(f2c_io_stream *f, double v) { "
        "f->list_character = false; (void)f2c_stream_putc(' ', f); f2c_io_write_real(f, v, "
        "DBL_DECIMAL_DIG); }\n"
        "static inline F2C_UNUSED void f2c_write_bool(f2c_io_stream *f, bool v) { "
        "f->list_character = false; f2c_stream_write_string(f, v ? \" T\" : \" F\"); }\n"
        "static inline F2C_UNUSED void f2c_write_character(f2c_io_stream *f, const char *v, "
        "size_t length) { const int quote = f->controls.delim == F2C_DELIM_APOSTROPHE ? "
        "'\\'' : f->controls.delim == F2C_DELIM_QUOTE ? '\"' : 0; if (!f->list_character "
        "|| quote != 0) (void)f2c_stream_putc(' ', f); f->list_character = quote == 0; "
        "if (quote != 0) (void)f2c_stream_putc(quote, f); for (size_t index = 0U; index "
        "< length; ++index) { (void)f2c_stream_putc((unsigned char)v[index], f); if (quote "
        "!= 0 && (unsigned char)v[index] == (unsigned)quote) (void)f2c_stream_putc(quote, f); "
        "} if (quote != 0) (void)f2c_stream_putc(quote, f); }\n"
        "static inline F2C_UNUSED void f2c_write_char(f2c_io_stream *f, char v) { "
        "f2c_write_character(f, &v, 1U); }\n"
        "static inline F2C_UNUSED void f2c_write_string(f2c_io_stream *f, const char *v) { "
        "f2c_write_character(f, v, strlen(v)); }\n");
}

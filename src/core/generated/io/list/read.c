#include "core/generated/private.h"

static void emit_character_list_io(Buffer *output) {
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED int f2c_read_character(f2c_io_stream *f, char *v, size_t "
        "length) { int c, quote = 0; bool closed; size_t i = 0U; do { c = f2c_stream_getc(f); } "
        "while (c "
        "!= EOF && (isspace((unsigned char)c) || c == f2c_io_value_separator(f))); if (c == EOF) "
        "return EOF; if (c "
        "== '\\'' || c == '\"') quote = c; else if (i < length) v[i++] = (char)c; closed = quote "
        "== 0; while ((c "
        "= f2c_stream_getc(f)) != EOF) { if (quote != 0) { if (c == '\\n' || c == '\\r') continue; "
        "if (c == quote) { int next = "
        "f2c_stream_getc(f); if (next == quote) c = next; else { if (next != EOF) "
        "(void)f2c_stream_ungetc(next, f); closed = true; break; } } } else if (isspace((unsigned "
        "char)c) || c "
        "== f2c_io_value_separator(f)) { (void)f2c_stream_ungetc(c, f); break; } if (i < length) "
        "v[i++] = (char)c; "
        "} if (!closed) return 0; if (i < length) memset(v + i, ' ', length - i); return 1; }\n"
        "static inline F2C_UNUSED int f2c_read_record(f2c_io_stream *f, char *v, size_t "
        "capacity) { size_t length = 0U; int c = 0; if (capacity == 0U) return 0; while (length + "
        "1U < capacity && (c = f2c_stream_getc(f)) != EOF && c != '\\n' && c != '\\r') "
        "v[length++] = (char)c; if (length == 0U && c == EOF) return EOF; if (c == '\\r') { "
        "int next = f2c_stream_getc(f); if (next != '\\n' && next != EOF) "
        "(void)f2c_stream_ungetc(next, f); } else if (c != '\\n' && c != EOF) { do { c = "
        "f2c_stream_getc(f); } while (c != '\\n' && c != EOF); } memset(v + length, ' ', "
        "capacity - length - 1U); v[capacity - 1U] = '\\0'; return 1; }\n"
        "static inline F2C_UNUSED void f2c_finish_read(f2c_io_stream *f) { int c; do { c = "
        "f2c_stream_getc(f); } while (c != '\\n' && c != EOF); }\n");
}

void f2c_emit_list_read_support(Buffer *output) {
    f2c_buffer_append(output, "static inline F2C_UNUSED int f2c_list_read_status(int status) { "
                              "return status > 0 ? F2C_IO_STATUS_OK : status == EOF ? EOF : "
                              "F2C_IO_STATUS_RECORD; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED int f2c_parse_integer_token(const char *token, int64_t "
        "minimum, int64_t maximum, int64_t *value) { char *end = NULL; long long parsed; "
        "errno = 0; parsed = strtoll(token, &end, 10); if (errno == ERANGE || end == token || "
        "*end != '\\0' || parsed < minimum || parsed > maximum) return 0; *value = "
        "(int64_t)parsed; return 1; }\n"
        "static inline F2C_UNUSED int f2c_read_integer_kind(f2c_io_stream *f, int64_t "
        "minimum, int64_t maximum, int64_t *value) { char *token; int status = "
        "f2c_io_read_token(f, 0, true, true, &token); if (status != 1) return status; "
        "status = f2c_parse_integer_token(token, minimum, maximum, value); free(token); "
        "return status; }\n"
        "static inline F2C_UNUSED int f2c_read_i32(f2c_io_stream *f, int32_t *v) { "
        "int64_t value; int r = f2c_read_integer_kind(f, INT32_MIN, INT32_MAX, &value); if (r == "
        "1) *v = "
        "(int32_t)value; return r; }\n"
        "static inline F2C_UNUSED int f2c_read_i8(f2c_io_stream *f, int8_t *v) { "
        "int64_t value; int r = f2c_read_integer_kind(f, INT8_MIN, INT8_MAX, &value); if (r == 1) "
        "*v = "
        "(int8_t)value; return r; }\n"
        "static inline F2C_UNUSED int f2c_read_i16(f2c_io_stream *f, int16_t *v) { "
        "int64_t value; int r = f2c_read_integer_kind(f, INT16_MIN, INT16_MAX, &value); if (r == "
        "1) *v = "
        "(int16_t)value; return r; }\n"
        "static inline F2C_UNUSED int f2c_read_i64(f2c_io_stream *f, int64_t *v) { "
        "int64_t value; int r = f2c_read_integer_kind(f, INT64_MIN, INT64_MAX, &value); if (r == "
        "1) *v = value; "
        "return r; }\n"
        "static inline F2C_UNUSED int f2c_read_real_kind(f2c_io_stream *f, int kind, "
        "double *value) { char *token; int status = f2c_io_read_token(f, 0, true, true, "
        "&token); if (status != 1) return status; status = f2c_io_parse_real(token, "
        "f->controls.decimal_comma, kind, f->controls.rounding, value); free(token); return "
        "status; }\n"
        "static inline F2C_UNUSED int f2c_read_float(f2c_io_stream *f, float *value) { double "
        "parsed; int status = f2c_read_real_kind(f, 4, &parsed); if (status == 1) *value = "
        "(float)parsed; return status; }\n"
        "static inline F2C_UNUSED int f2c_read_double(f2c_io_stream *f, double *value) { "
        "return f2c_read_real_kind(f, 8, value); }\n"
        "static inline F2C_UNUSED int f2c_read_bool(f2c_io_stream *f, bool *v) { char "
        "*token; const char *begin; int first, status = f2c_io_read_token(f, 0, true, true, "
        "&token); if (status != 1) return status; begin = token; if (*begin == '.') "
        "++begin; first = tolower((unsigned char)*begin); if (first == 't' || first == 'f') "
        "*v = first == 't'; else status = 0; free(token); return status; }\n"
        "static inline F2C_UNUSED int f2c_read_char(f2c_io_stream *f, char *v) { int c; do { c "
        "= f2c_stream_getc(f); } while (c != EOF && isspace((unsigned char)c)); if (c == EOF) "
        "return EOF; *v = (char)c; return 1; }\n");
    emit_character_list_io(output);
}

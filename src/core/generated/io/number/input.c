#include "core/generated/private.h"

void f2c_emit_io_number_input_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED char *f2c_io_canonical_number(const char *token, bool "
        "decimal_comma) { size_t length, out = 0U; char *copy; bool exponent = false; while "
        "(isspace((unsigned char)*token)) ++token; length = strlen(token); while (length > "
        "0U && isspace((unsigned char)token[length - 1U])) --length; if (length == 0U || "
        "length > SIZE_MAX - 2U) return NULL; copy = (char *)malloc(length + 2U); if (copy "
        "== NULL) return NULL; for (size_t index = 0U; index < length; ++index) { char c = "
        "token[index]; if (c == 'd' || c == 'D' || c == 'e' || c == 'E') { c = 'e'; "
        "exponent = true; } if (decimal_comma && c == ',') c = '.'; if (!exponent && "
        "index > 0U && (c == '+' || c == '-') && (isdigit((unsigned char)token[index - 1U]) "
        "|| token[index - 1U] == '.' || token[index - 1U] == ',')) { copy[out++] = 'e'; "
        "exponent = true; } copy[out++] = c; } copy[out] = '\\0'; return copy; }\n"
        "static inline F2C_UNUSED char *f2c_io_locale_number(char *canonical) { "
        "struct lconv *locale = localeconv(); const char *point = locale != NULL ? "
        "locale->decimal_point : NULL; size_t point_length = point != NULL ? strlen(point) "
        ": 0U; char *decimal, *copy; size_t length, offset; if (point_length == 0U || "
        "(point_length == 1U && point[0] == '.')) return canonical; decimal = strchr("
        "canonical, '.'); if (decimal == NULL) return canonical; length = strlen(canonical); "
        "if (point_length > SIZE_MAX - length) return NULL; copy = (char *)malloc(length + "
        "point_length); if (copy == NULL) return NULL; offset = (size_t)(decimal - canonical); "
        "memcpy(copy, canonical, offset); memcpy(copy + offset, point, point_length); "
        "memcpy(copy + offset + point_length, decimal + 1, length - offset); return copy; }\n"
        "static inline F2C_UNUSED bool f2c_io_decimal_token_valid(const char *token) { "
        "bool digit = false; if (*token == '+' || *token == '-') ++token; while "
        "(isdigit((unsigned char)*token)) { digit = true; ++token; } if (*token == '.') { "
        "++token; while (isdigit((unsigned char)*token)) { digit = true; ++token; } } if "
        "(!digit) return false; if (*token == 'e') { bool exponent_digit = false; ++token; "
        "if (*token == '+' || *token == '-') ++token; while (isdigit((unsigned char)*token)) "
        "{ exponent_digit = true; ++token; } if (!exponent_digit) return false; } return "
        "*token == '\\0'; }\n"
        "static inline F2C_UNUSED int f2c_io_parse_real(const char *token, bool comma, "
        "int kind, f2c_format_round_mode mode, double *value) { char *canonical = "
        "f2c_io_canonical_number(token, comma), *localized, *end = NULL; double parsed; "
        "bool numeric; int valid, saved = -1; if (canonical == NULL) return 0; numeric = "
        "f2c_io_decimal_token_valid(canonical); if (!numeric) { const char *special = "
        "canonical; if (*special == '+' || *special == '-') ++special; if "
        "(!f2c_option_equal(special, strlen(special), \"inf\") && !f2c_option_equal(special, "
        "strlen(special), \"infinity\") && !f2c_option_equal(special, strlen(special), "
        "\"nan\")) { free(canonical); return 0; } } localized = "
        "f2c_io_locale_number(canonical); if (localized == NULL) { free(canonical); return "
        "0; } if (numeric && mode != F2C_FORMAT_ROUND_PROCESSOR && "
        "!f2c_io_begin_rounding(F2C_FORMAT_ROUND_NEAREST, 0.0, 0, false, &saved)) { "
        "if (localized != canonical) free(localized); free(canonical); return 0; } "
        "errno = 0; if (kind == 4) parsed = (double)strtof(localized, &end); else parsed "
        "= strtod(localized, &end); valid = end != localized && *end == '\\0' && "
        "!(errno == ERANGE && isinf(parsed)); if (localized != canonical) free(localized); "
        "f2c_io_end_rounding(saved); "
        "if (valid && numeric) valid = f2c_io_adjust_real(canonical, kind, mode, &parsed); "
        "free(canonical); if (valid) *value = parsed; return valid; }\n");
}

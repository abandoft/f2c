#include "core/generated/private.h"

/* Binary32/64 dyadics have at most 768 decimal coefficient digits. The
 * fixed workspace is a representation bound, not a bound on input fields. */
void f2c_emit_io_number_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED size_t f2c_io_dyadic_digits(uint64_t coefficient, int "
        "power, char digits[1200], int *decimal_power) { uint32_t limbs[128] = {0}; size_t "
        "count = 0U, length = 0U; unsigned multiplier = power < 0 ? 5U : 2U; unsigned steps "
        "= (unsigned)(power < 0 ? -power : power); *decimal_power = power < 0 ? power : 0; "
        "do { limbs[count++] = (uint32_t)(coefficient % UINT64_C(1000000000)); coefficient "
        "/= UINT64_C(1000000000); } while (coefficient != 0U); for (unsigned step = 0U; "
        "step < steps; ++step) { uint64_t carry = 0U; for (size_t index = 0U; index < count; "
        "++index) { uint64_t value = (uint64_t)limbs[index] * multiplier + carry; limbs[index] "
        "= (uint32_t)(value % UINT64_C(1000000000)); carry = value / UINT64_C(1000000000); } "
        "if (carry != 0U) { if (count == 128U) return 0U; limbs[count++] = (uint32_t)carry; } "
        "} for (size_t index = count; index != 0U; --index) { int written = snprintf(digits "
        "+ length, 1200U - length, index == count ? \"%u\" : \"%09u\", "
        "(unsigned)limbs[index - 1U]); if (written < 0 || (size_t)written >= 1200U - length) "
        "return 0U; length += (size_t)written; } return length; }\n"
        "static inline F2C_UNUSED void f2c_io_binary_parts(uint64_t bits, int kind, "
        "uint64_t *coefficient, int *power) { const unsigned fraction = kind == 4 ? 23U : "
        "52U; const unsigned bias = kind == 4 ? 127U : 1023U; const uint64_t fraction_mask = "
        "(UINT64_C(1) << fraction) - UINT64_C(1); const unsigned exponent = (unsigned)(bits "
        ">> fraction); *coefficient = bits & fraction_mask; if (exponent != 0U) "
        "*coefficient |= UINT64_C(1) << fraction; *power = (int)(exponent != 0U ? exponent : "
        "1U) - (int)bias - (int)fraction; }\n"
        "static inline F2C_UNUSED int f2c_io_decimal_compare(const char *token, uint64_t "
        "coefficient, int power) { char digits[1200]; int decimal_power; size_t length, "
        "total = 0U, leading = 0U, fractional = 0U; const char *begin, *end, *cursor, "
        "*exponent; int64_t input_power = 0; bool nonzero = false, after_point = false; if "
        "(*token == '+' || *token == '-') ++token; begin = token; exponent = strchr(token, "
        "'e'); if (exponent == NULL) exponent = strchr(token, 'E'); end = exponent != NULL "
        "? exponent : token + strlen(token); for (cursor = begin; cursor < end; ++cursor) { "
        "if (*cursor == '.') { after_point = true; continue; } ++total; if (after_point) "
        "++fractional; if (!nonzero) { if (*cursor == '0') ++leading; else nonzero = true; } "
        "} if (!nonzero) return coefficient == 0U ? 0 : -1; if (coefficient == 0U) return "
        "1; if (exponent != NULL) { bool negative; cursor = exponent + 1; negative = "
        "*cursor == '-'; if (*cursor == '+' || *cursor == '-') ++cursor; while "
        "(*cursor != '\\0') { if (input_power < INT64_C(1000000000)) input_power = "
        "input_power * INT64_C(10) + (int64_t)(*cursor - '0'); ++cursor; } if (negative) "
        "input_power = -input_power; } input_power += (int64_t)(total - leading) - "
        "(int64_t)fractional; length = f2c_io_dyadic_digits(coefficient, power, digits, "
        "&decimal_power); if (length == 0U) return 2; if (input_power != (int64_t)length + "
        "decimal_power) return input_power < (int64_t)length + decimal_power ? -1 : 1; "
        "cursor = begin; while (cursor < end && (*cursor == '0' || *cursor == '.')) ++cursor; "
        "for (size_t index = 0U; cursor < end || index < length; ++index) { int left, right; "
        "if (cursor < end && *cursor == '.') ++cursor; left = cursor < end ? "
        "(unsigned char)*cursor++ : '0'; right = index < length ? (unsigned char)digits[index] "
        ": '0'; if (left != right) return left < right ? -1 : 1; } return 0; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED bool f2c_io_adjust_real(const char *token, int kind, "
        "f2c_format_round_mode mode, double *value) { uint64_t bits, sign, coefficient; "
        "int power, relation, direction = 0; const uint64_t sign_mask = kind == 4 ? "
        "UINT64_C(0x80000000) : UINT64_C(0x8000000000000000); const uint64_t maximum = "
        "kind == 4 ? UINT64_C(0x7f7fffff) : UINT64_C(0x7fefffffffffffff); if (mode == "
        "F2C_FORMAT_ROUND_PROCESSOR || !isfinite(*value)) return true; if (kind == 4) { "
        "float narrow = (float)*value; uint32_t word; memcpy(&word, &narrow, sizeof(word)); "
        "bits = word; } else memcpy(&bits, value, sizeof(bits)); sign = bits & sign_mask; "
        "bits &= sign_mask - UINT64_C(1); f2c_io_binary_parts(bits, kind, &coefficient, "
        "&power); relation = f2c_io_decimal_compare(token, coefficient, power); if "
        "(relation == 2) return false; if (relation == 0) return true; if (mode == "
        "F2C_FORMAT_ROUND_ZERO || (mode == F2C_FORMAT_ROUND_UP && sign != 0U) || (mode == "
        "F2C_FORMAT_ROUND_DOWN && sign == 0U)) direction = relation < 0 ? -1 : 0; else if "
        "(mode == F2C_FORMAT_ROUND_UP || mode == F2C_FORMAT_ROUND_DOWN) direction = "
        "relation > 0 ? 1 : 0; else { uint64_t lower = relation > 0 ? bits : bits - "
        "UINT64_C(1); int halfway; f2c_io_binary_parts(lower, kind, &coefficient, &power); "
        "halfway = f2c_io_decimal_compare(token, coefficient * UINT64_C(2) + UINT64_C(1), "
        "power - 1); if (halfway == 2) return false; if (halfway > 0 || (halfway == 0 && "
        "(mode == F2C_FORMAT_ROUND_COMPATIBLE || (lower & UINT64_C(1)) != 0U))) bits = "
        "lower + UINT64_C(1); else bits = lower; } if (direction > 0) ++bits; else if "
        "(direction < 0) --bits; if (bits > maximum) return false; bits |= sign; if (kind == "
        "4) { uint32_t word = (uint32_t)bits; float narrow; memcpy(&narrow, &word, "
        "sizeof(narrow)); *value = (double)narrow; } else memcpy(value, &bits, sizeof(bits)); "
        "return true; }\n"
        "static inline F2C_UNUSED bool f2c_io_binary_halfway(double value, int precision, "
        "bool significant) { uint64_t bits, coefficient; int power, decimal_power; char "
        "digits[1200]; size_t length, trimmed; if (!isfinite(value) || value == 0.0 || "
        "precision < 0) return false; memcpy(&bits, &value, sizeof(bits)); bits &= "
        "UINT64_C(0x7fffffffffffffff); f2c_io_binary_parts(bits, 8, &coefficient, &power); "
        "length = f2c_io_dyadic_digits(coefficient, power, digits, &decimal_power); if "
        "(length == 0U) return false; trimmed = length; while (trimmed > 0U && "
        "digits[trimmed - 1U] == '0') --trimmed; if (trimmed == 0U || digits[trimmed - 1U] "
        "!= '5') return false; return significant ? trimmed == (size_t)precision + 1U : "
        "(int64_t)decimal_power + (int64_t)(length - trimmed) == -(int64_t)precision - 1; }\n"
        "static inline F2C_UNUSED int f2c_io_rounding_target(f2c_format_round_mode mode, "
        "double value, int precision, bool significant) { switch (mode) { case "
        "F2C_FORMAT_ROUND_UP: return FE_UPWARD; case F2C_FORMAT_ROUND_DOWN: return "
        "FE_DOWNWARD; case F2C_FORMAT_ROUND_ZERO: return FE_TOWARDZERO; case "
        "F2C_FORMAT_ROUND_NEAREST: return FE_TONEAREST; case F2C_FORMAT_ROUND_COMPATIBLE: "
        "return f2c_io_binary_halfway(value, precision, significant) ? (signbit(value) ? "
        "FE_DOWNWARD : FE_UPWARD) : FE_TONEAREST; default: return -1; } }\n"
        "static inline F2C_UNUSED bool f2c_io_begin_rounding(f2c_format_round_mode mode, "
        "double value, int precision, bool significant, int *saved) { int target; *saved = "
        "fegetround(); target = f2c_io_rounding_target(mode, value, precision, significant); "
        "return target < 0 || (*saved >= 0 && (target == *saved || fesetround(target) == 0)); "
        "}\n"
        "static inline F2C_UNUSED void f2c_io_end_rounding(int saved) { if (saved >= 0 && "
        "fegetround() != saved) (void)fesetround(saved); }\n");
}

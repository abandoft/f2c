#include "core/generated/private.h"

void f2c_emit_descriptor_state_support(Buffer *output) {
    f2c_buffer_append(
        output,
        "#define F2C_STATE_READ(d, field, type, qualifiers) "
        "(((qualifiers) & 1U) != 0U ? "
        "*((type const volatile *)&((d)->field)) : (d)->field)\n"
        "static inline F2C_UNUSED void *f2c_descriptor_state_data("
        "const f2c_descriptor *state, unsigned int qualifiers) { "
        "return state == NULL ? NULL : F2C_STATE_READ(state, data, void *, qualifiers); }\n"
        "static inline F2C_UNUSED const void *f2c_descriptor_state_readonly_data("
        "const f2c_descriptor *state, unsigned int qualifiers) { "
        "return state == NULL ? NULL : F2C_STATE_READ(state, readonly_data, const void *, "
        "qualifiers); }\n"
        "static inline F2C_UNUSED int32_t f2c_descriptor_state_lower("
        "const f2c_descriptor *state, size_t dimension, unsigned int qualifiers) { "
        "int64_t value; if (state == NULL) return 1; if (dimension >= 15U || "
        "dimension >= state->rank) abort(); "
        "value = F2C_STATE_READ(state, lower[dimension], int64_t, qualifiers); "
        "if (value < INT32_MIN || value > INT32_MAX) abort(); return (int32_t)value; }\n"
        "static inline F2C_UNUSED int32_t f2c_descriptor_state_extent("
        "const f2c_descriptor *state, size_t dimension, unsigned int qualifiers) { "
        "int64_t value; if (state == NULL) return 0; if (dimension >= 15U || "
        "dimension >= state->rank) abort(); "
        "value = F2C_STATE_READ(state, extent[dimension], int64_t, qualifiers); "
        "if (value < 0 || value > INT32_MAX) abort(); return (int32_t)value; }\n"
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_state_stride("
        "const f2c_descriptor *state, size_t dimension, unsigned int qualifiers) { "
        "if (state == NULL) return 0; if (dimension >= 15U || dimension >= state->rank) abort(); "
        "return F2C_STATE_READ(state, stride[dimension], ptrdiff_t, qualifiers); }\n"
        "static inline F2C_UNUSED size_t f2c_descriptor_state_character_length("
        "const f2c_descriptor *state, unsigned int qualifiers) { "
        "return state == NULL ? 0U : F2C_STATE_READ(state, character_length, size_t, qualifiers); "
        "}\n"
        "static inline F2C_UNUSED bool f2c_descriptor_state_deallocatable("
        "const f2c_descriptor *state, unsigned int qualifiers) { "
        "return state != NULL && F2C_STATE_READ(state, deallocatable, bool, qualifiers); }\n"
        "#undef F2C_STATE_READ\n");
}

#include "core/generated/private.h"

/* The generated descriptor contract is emitted once, independently of program
 * units and expression lowering. Offsets, bounds and copy preparation share
 * these checked operations instead of implementing their own ABI arithmetic. */
void f2c_emit_descriptor_layout_support(Buffer *output) {
    f2c_buffer_append(output, "static inline F2C_UNUSED bool f2c_descriptor_data_absent("
                              "const volatile void *data) { return data == NULL; }\n");
    f2c_buffer_append(
        output, "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_record_stride(size_t bytes) { "
                "if (bytes > (size_t)PTRDIFF_MAX) abort(); return (ptrdiff_t)bytes; }\n");
    f2c_buffer_append(output,
                      "static inline F2C_UNUSED size_t f2c_array_offset(int64_t subscript, "
                      "int64_t lower, size_t extent) { uint64_t offset; if (subscript < lower) "
                      "abort(); offset = (uint64_t)subscript - (uint64_t)lower; if (offset >= "
                      "(uint64_t)extent) abort(); return (size_t)offset; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_stride_multiply(ptrdiff_t a, "
        "ptrdiff_t b) { if (a > 0 ? (b > 0 ? a > PTRDIFF_MAX / b : b < PTRDIFF_MIN / a) "
        ": a < 0 ? (b > 0 ? a < PTRDIFF_MIN / b : b < 0 && a < PTRDIFF_MAX / b) : "
        "false) abort(); return a * b; }\n"
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_stride_extent(ptrdiff_t stride, "
        "size_t extent) { if (extent > (size_t)PTRDIFF_MAX) abort(); return "
        "f2c_descriptor_stride_multiply(stride, (ptrdiff_t)extent); }\n"
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_stride_step(ptrdiff_t stride, "
        "int64_t step) { if (step == 0 || step < (int64_t)PTRDIFF_MIN || step > "
        "(int64_t)PTRDIFF_MAX) abort(); return f2c_descriptor_stride_multiply(stride, "
        "(ptrdiff_t)step); }\n"
        "static inline F2C_UNUSED size_t f2c_section_extent(int64_t first, int64_t last, "
        "int64_t step) { uint64_t distance; uint64_t magnitude; uint64_t quotient; if "
        "(step == 0) abort(); if (step > 0) { if (last < first) return 0U; distance = "
        "(uint64_t)last - (uint64_t)first; magnitude = (uint64_t)step; } else { if (last > "
        "first) return 0U; distance = (uint64_t)first - (uint64_t)last; magnitude = "
        "(uint64_t)(-(step + 1)) + UINT64_C(1); } quotient = distance / magnitude; if "
        "(quotient >= (uint64_t)SIZE_MAX) abort(); return (size_t)(quotient + "
        "UINT64_C(1)); }\n"
        "static inline F2C_UNUSED bool f2c_descriptor_is_contiguous(size_t rank, const "
        "size_t *extents, const ptrdiff_t *strides, size_t record_size) { size_t dimension; "
        "ptrdiff_t expected; if (rank > 15U || record_size > (size_t)PTRDIFF_MAX) abort(); "
        "expected = (ptrdiff_t)record_size; "
        "for (dimension = 0U; dimension < rank; ++dimension) if (extents[dimension] == 0U) "
        "return true; for (dimension = 0U; dimension < rank; ++dimension) { if "
        "(extents[dimension] > 1U && strides[dimension] != expected) return false; expected = "
        "f2c_descriptor_stride_extent(expected, extents[dimension]); } return true; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_offset_add(ptrdiff_t left, "
        "ptrdiff_t right) { if ((right > 0 && left > PTRDIFF_MAX - right) || (right < 0 && "
        "left < PTRDIFF_MIN - right)) abort(); return left + right; }\n"
        "static inline F2C_UNUSED size_t f2c_descriptor_element_count(const "
        "f2c_descriptor *descriptor) { size_t dimension; size_t count = 1U; if "
        "(descriptor == NULL || descriptor->rank == 0U || descriptor->rank > 15U) abort(); "
        "for (dimension = 0U; dimension < descriptor->rank; ++dimension) { size_t extent; "
        "if (descriptor->extent[dimension] < 0) abort(); extent = "
        "(size_t)descriptor->extent[dimension]; if (extent == 0U) return 0U; if (count > "
        "SIZE_MAX / extent) abort(); count *= extent; } return count; }\n"
        "static inline F2C_UNUSED size_t f2c_descriptor_record_size(const f2c_descriptor "
        "*descriptor, bool character) { if (descriptor == NULL) abort(); return character "
        "? descriptor->character_length : descriptor->element_size; }\n"
        "static inline F2C_UNUSED ptrdiff_t f2c_descriptor_linear_byte_offset(const "
        "f2c_descriptor *descriptor, size_t index) { size_t dimension; ptrdiff_t offset = "
        "0; if (descriptor == NULL || descriptor->rank == 0U || descriptor->rank > 15U) "
        "abort(); for (dimension = 0U; dimension < descriptor->rank; ++dimension) { "
        "uint64_t raw_extent; size_t extent; size_t ordinal; if "
        "(descriptor->extent[dimension] <= 0) abort(); raw_extent = "
        "(uint64_t)descriptor->extent[dimension]; if (raw_extent > (uint64_t)SIZE_MAX) "
        "abort(); extent = (size_t)raw_extent; ordinal = index % extent; index /= "
        "extent; if (ordinal > (size_t)PTRDIFF_MAX) abort(); offset = "
        "f2c_descriptor_offset_add(offset, f2c_descriptor_stride_multiply("
        "descriptor->byte_stride[dimension], (ptrdiff_t)ordinal)); } if (index != 0U) abort(); "
        "return offset; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED ptrdiff_t f2c_array_descriptor_byte_offset(size_t rank, const "
        "int64_t *subscripts, const int64_t *lowers, const size_t *extents, const ptrdiff_t "
        "*strides) { size_t dimension; ptrdiff_t result = 0; if (rank == 0U || rank > 15U || "
        "subscripts == NULL || lowers == NULL || extents == NULL || strides == NULL) abort(); "
        "for (dimension = 0U; dimension "
        "< rank; ++dimension) { size_t ordinal = f2c_array_offset(subscripts[dimension], "
        "lowers[dimension], extents[dimension]); if (ordinal > (size_t)PTRDIFF_MAX) abort(); "
        "result = f2c_descriptor_offset_add(result, f2c_descriptor_stride_multiply("
        "(ptrdiff_t)ordinal, strides[dimension])); } return result; }\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED bool f2c_descriptor_span_valid(const f2c_descriptor "
        "*descriptor,\n"
        "    size_t width, size_t alignment) {\n"
        "    uintmax_t negative = 0U, positive; bool empty = width == 0U;\n"
        "    const uintmax_t limit = (uintmax_t)PTRDIFF_MAX;\n"
        "    uintptr_t address;\n"
        "    if (descriptor == NULL || descriptor->rank > 15U) return false;\n"
        "    address = (uintptr_t)descriptor->readonly_data;\n"
        "    if (width > (size_t)PTRDIFF_MAX || alignment == 0U || address % alignment != 0U)\n"
        "        return false;\n"
        "    for (size_t dimension = 0U; dimension < descriptor->rank; ++dimension) {\n"
        "        if (descriptor->extent[dimension] < 0) return false;\n"
        "        if (descriptor->extent[dimension] == 0) empty = true;\n"
        "    }\n"
        "    if (empty) return true;\n"
        "    positive = (uintmax_t)(width - 1U);\n"
        "    for (size_t dimension = 0U; dimension < descriptor->rank; ++dimension) {\n"
        "        const uintmax_t count = (uintmax_t)(descriptor->extent[dimension] - 1);\n"
        "        const ptrdiff_t stride = descriptor->byte_stride[dimension];\n"
        "        const uintmax_t magnitude = stride < 0\n"
        "            ? (uintmax_t)(-(stride + 1)) + UINTMAX_C(1) : (uintmax_t)stride;\n"
        "        const uintmax_t available = stride < 0 ? limit + UINTMAX_C(1) - negative\n"
        "                                                 : limit - positive;\n"
        "        if (count == 0U) continue;\n"
        "        if (magnitude % alignment != 0U || magnitude > available / count) return false;\n"
        "        if (stride < 0) negative += magnitude * count;\n"
        "        else positive += magnitude * count;\n"
        "    }\n"
        "    return address == 0U || (negative <= (uintmax_t)address &&\n"
        "        positive <= (uintmax_t)(UINTPTR_MAX - address));\n"
        "}\n");
    f2c_buffer_append(
        output,
        "static inline F2C_UNUSED bool f2c_descriptor_same_target(const f2c_descriptor *pointer, "
        "const f2c_descriptor *target, bool character) { if (pointer == NULL || target == NULL || "
        "pointer->readonly_data == NULL || pointer->readonly_data != target->readonly_data || "
        "pointer->rank == 0U || pointer->rank > 15U || pointer->rank != target->rank || "
        "(character && (pointer->character_length == 0U || "
        "pointer->character_length != target->character_length))) return false; "
        "for (size_t dimension = 0U; dimension < pointer->rank; ++dimension) { "
        "if (pointer->extent[dimension] <= 0 || pointer->extent[dimension] != "
        "target->extent[dimension] || "
        "(pointer->extent[dimension] > 1 && pointer->byte_stride[dimension] != "
        "target->byte_stride[dimension])) "
        "return false; } return true; }\n");
    f2c_buffer_append(
        output, "static inline F2C_UNUSED bool f2c_size_multiply(size_t left, size_t right, "
                "size_t *result) { if (right != 0U && left > SIZE_MAX / right) return false; "
                "*result = left * right; return true; }\n"
                "static inline F2C_UNUSED bool f2c_default_integer_bounds(int64_t lower, "
                "size_t extent) { return lower >= (int64_t)INT32_MIN && lower <= "
                "(int64_t)INT32_MAX && extent <= (size_t)INT32_MAX; }\n"
                "static inline F2C_UNUSED bool f2c_descriptor_bridge_valid(const "
                "f2c_descriptor *descriptor, size_t rank, size_t element_size, size_t alignment, "
                "bool character) { size_t "
                "dimension; if (descriptor == NULL || descriptor->rank != rank || "
                "descriptor->element_size != element_size || rank > 15U || element_size == 0U || "
                "(descriptor->storage_qualifiers & ~3U) != 0U) return false; for "
                "(dimension = 0U; dimension < rank; ++dimension) { int64_t extent = "
                "descriptor->extent[dimension]; if (extent < 0 || extent > INT32_MAX || "
                "!f2c_default_integer_bounds(descriptor->lower[dimension], (size_t)extent) || "
                "(extent > 1 && descriptor->byte_stride[dimension] == 0 && "
                "(!character || descriptor->character_length != 0U))) return false; } return "
                "f2c_descriptor_span_valid(descriptor, "
                "f2c_descriptor_record_size(descriptor, character), alignment); }\n");
}

#include "core/generated/private.h"

/* F2C_REDUCTION_ACCESS/NAME are set by the caller for ordinary and volatile
 * views. Mask and data are read only when selected; each selected datum is
 * loaded once. The first datum is not combined with an artificial identity.
 */
void f2c_emit_extremum_reduction_kernels(Buffer *output) {
    f2c_buffer_append(
        output,
        "#define F2C_DEFINE_EXTREMA(s, t, low, high) "
        "static inline F2C_UNUSED t F2C_REDUCTION_NAME(f2c_maxval_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d) { "
        "if (n == 0U) return (low); t r = v[0]; for (size_t i = 1U; i < n; ++i) { "
        "t x = v[(ptrdiff_t)i * d]; r = F2C_FORTRAN_MAX(r, x); } return r; } "
        "static inline F2C_UNUSED t F2C_REDUCTION_NAME(f2c_minval_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d) { "
        "if (n == 0U) return (high); t r = v[0]; for (size_t i = 1U; i < n; ++i) { "
        "t x = v[(ptrdiff_t)i * d]; r = F2C_FORTRAN_MIN(r, x); } return r; } "
        "static inline F2C_UNUSED int32_t F2C_REDUCTION_NAME(f2c_maxloc_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d) { "
        "if (n == 0U) return 0; size_t p = 0U; t best = v[0]; "
        "for (size_t i = 1U; i < n; ++i) { t x = v[(ptrdiff_t)i * d]; "
        "if (F2C_MAXIMUM_SELECT(x, best, false)) { best = x; p = i; } } "
        "if (p >= (size_t)INT32_MAX) abort(); return (int32_t)p + INT32_C(1); } "
        "static inline F2C_UNUSED int32_t F2C_REDUCTION_NAME(f2c_minloc_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d) { "
        "if (n == 0U) return 0; size_t p = 0U; t best = v[0]; "
        "for (size_t i = 1U; i < n; ++i) { t x = v[(ptrdiff_t)i * d]; "
        "if (F2C_MINIMUM_SELECT(x, best, false)) { best = x; p = i; } } "
        "if (p >= (size_t)INT32_MAX) abort(); return (int32_t)p + INT32_C(1); } "
        "static inline F2C_UNUSED t F2C_REDUCTION_NAME(f2c_maxval_mask_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d, "
        "const F2C_REDUCTION_ACCESS void *m, size_t ms, ptrdiff_t md, bool scalar) { "
        "t r = (low); bool found = false; for (size_t i = 0U; i < n; ++i) "
        "if (F2C_REDUCTION_NAME(f2c_reduction_selected)(m, ms, md, scalar, i)) { "
        "t x = v[(ptrdiff_t)i * d]; r = found ? F2C_FORTRAN_MAX(r, x) : x; "
        "found = true; } return r; } "
        "static inline F2C_UNUSED t F2C_REDUCTION_NAME(f2c_minval_mask_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d, "
        "const F2C_REDUCTION_ACCESS void *m, size_t ms, ptrdiff_t md, bool scalar) { "
        "t r = (high); bool found = false; for (size_t i = 0U; i < n; ++i) "
        "if (F2C_REDUCTION_NAME(f2c_reduction_selected)(m, ms, md, scalar, i)) { "
        "t x = v[(ptrdiff_t)i * d]; r = found ? F2C_FORTRAN_MIN(r, x) : x; "
        "found = true; } return r; } "
        "static inline F2C_UNUSED int64_t F2C_REDUCTION_NAME(f2c_maxloc_mask_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d, "
        "const F2C_REDUCTION_ACCESS void *m, size_t ms, ptrdiff_t md, bool scalar, bool back) { "
        "size_t p = 0U; bool found = false; t best = (low); "
        "for (size_t i = 0U; i < n; ++i) "
        "if (F2C_REDUCTION_NAME(f2c_reduction_selected)(m, ms, md, scalar, i)) { "
        "t x = v[(ptrdiff_t)i * d]; if (!found || F2C_MAXIMUM_SELECT(x, best, back)) { "
        "p = i; found = true; best = x; } } "
        "if (!found) return INT64_C(0); if (p >= (size_t)INT64_MAX) abort(); "
        "return (int64_t)p + INT64_C(1); } "
        "static inline F2C_UNUSED int64_t F2C_REDUCTION_NAME(f2c_minloc_mask_##s)("
        "const F2C_REDUCTION_ACCESS t *v, size_t n, ptrdiff_t d, "
        "const F2C_REDUCTION_ACCESS void *m, size_t ms, ptrdiff_t md, bool scalar, bool back) { "
        "size_t p = 0U; bool found = false; t best = (high); "
        "for (size_t i = 0U; i < n; ++i) "
        "if (F2C_REDUCTION_NAME(f2c_reduction_selected)(m, ms, md, scalar, i)) { "
        "t x = v[(ptrdiff_t)i * d]; if (!found || F2C_MINIMUM_SELECT(x, best, back)) { "
        "p = i; found = true; best = x; } } "
        "if (!found) return INT64_C(0); if (p >= (size_t)INT64_MAX) abort(); "
        "return (int64_t)p + INT64_C(1); }\n"
        "F2C_DEFINE_EXTREMA(i8, int8_t, INT8_MIN, INT8_MAX)\n"
        "F2C_DEFINE_EXTREMA(i16, int16_t, INT16_MIN, INT16_MAX)\n"
        "F2C_DEFINE_EXTREMA(i32, int32_t, INT32_MIN, INT32_MAX)\n"
        "F2C_DEFINE_EXTREMA(i64, int64_t, INT64_MIN, INT64_MAX)\n"
        "F2C_DEFINE_EXTREMA(f, float, -FLT_MAX, FLT_MAX)\n"
        "F2C_DEFINE_EXTREMA(d, double, -DBL_MAX, DBL_MAX)\n"
        "#undef F2C_DEFINE_EXTREMA\n");
}
